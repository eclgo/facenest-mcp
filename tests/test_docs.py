# -*- coding: utf-8 -*-
"""Documentation self-sufficiency gate: the docs must cover every tool, every error code
the rule enums, and must not drift away from the code.

Why this test exists: the docs are the only "world knowledge" a weak model has. Drift
raises no error - it just makes the model talk nonsense in front of the user - so "the
docs must contain X" is made into an executable assertion.
"""
import os
import re
import sys
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "scripts"))   # the doc generators live here

from facenest_mcp import errors, server  # noqa: E402


def read(*parts):
    with open(os.path.join(ROOT, *parts), encoding="utf-8") as fh:
        return fh.read()


class ToolsDocTest(unittest.TestCase):
    def test_every_tool_has_a_useful_description(self):
        for tool in server.TOOLS:
            desc = tool.get("description", "")
            self.assertGreaterEqual(len(desc), 120, tool["name"])
            self.assertIn("Returns", desc, tool["name"])

    def test_readme_lists_every_tool(self):
        names = [t["name"] for t in server.TOOLS]
        for readme in ("README.md", "README.zh-CN.md"):
            text = read(readme)
            for name in names:
                self.assertIn(name, text, f"{readme} missing {name}")

    def test_agent_guide_covers_every_tool(self):
        guide = read("docs", "AGENT_GUIDE.md")
        for name in [t["name"] for t in server.TOOLS]:
            self.assertIn(name, guide, name)

    def test_agent_guide_covers_every_error_code(self):
        guide = read("docs", "AGENT_GUIDE.md")
        for code in errors.HINTS:
            self.assertIn(code, guide, code)
        self.assertIn("ERR_SMART_", guide)

    def test_agent_guide_lists_rule_enums(self):
        guide = read("docs", "AGENT_GUIDE.md")
        for token in ("is_not", "not_has", "last_days", "this_month", "admin1", "Max 30 rules"):
            self.assertIn(token, guide, token)

    def test_system_prompt_is_verbatim_in_both_guides(self):
        prompt = server.AGENT_PROMPT.strip()
        for guide in ("docs/AGENT_GUIDE.md", "docs/AGENT_GUIDE.zh-CN.md"):
            self.assertIn(prompt, read(guide), guide)

    def test_zh_guide_exists_and_covers_tools(self):
        guide = read("docs", "AGENT_GUIDE.zh-CN.md")
        for name in [t["name"] for t in server.TOOLS]:
            self.assertIn(name, guide, name)

    def test_no_absolute_local_paths_leak_into_docs(self):
        """The developer's own drives (C:\\ and H:\\) must never appear in a public page.
        The destination folders shown in the demo pages are D:\\ on purpose."""
        local = re.compile(r"[CH]:\\")
        for guide in ("docs/AGENT_GUIDE.md", "docs/AGENT_GUIDE.zh-CN.md",
                      "README.md", "README.zh-CN.md"):
            self.assertNotRegex(read(guide), local, guide)

    def test_tools_txt_equals_the_live_tool_schema(self):
        """`docs/_generated/_tools.txt` is a generated artifact (the generator is
        `scripts/_dump_tools.py`, and the test imports its `render`, so the expected text is the
        generator's own output).

        Drift here is invisible to a user: the docs would advertise a tool, a parameter or a
        quota that the app does not have. So the file is compared line for line with the
        single source of truth - `server.TOOLS`. Fix by running: python scripts/_dump_tools.py
        """
        import _dump_tools
        expected = _dump_tools.render(server.TOOLS).replace("\r\n", "\n")
        actual = read("docs", "_generated", "_tools.txt").replace("\r\n", "\n")
        self.assertEqual(expected, actual,
                         "docs/_generated/_tools.txt is stale - run: python scripts/_dump_tools.py")
        self.assertEqual(actual.split("\n")[0], "count=%d" % len(server.TOOLS))

    def test_tools_md_equals_the_generated_doc(self):
        """`docs/TOOLS.md` is generated by `scripts/gen_tools_doc.py`; the expected text is that
        generator's own output, so the page can only ever say what the code says (parameters,
        read/write label, limits quoted from each tool's description). The generator also refuses
        to render when its group map does not cover exactly the tools the code exposes.
        Fix by running: python scripts/gen_tools_doc.py
        """
        sys.path.insert(0, os.path.join(ROOT, "scripts"))
        import gen_tools_doc
        expected = gen_tools_doc.render(server.TOOLS).replace("\r\n", "\n")
        actual = read("docs", "TOOLS.md").replace("\r\n", "\n")
        self.assertEqual(expected, actual,
                         "docs/TOOLS.md is stale - run: python scripts/gen_tools_doc.py")
        names = [t["name"] for t in server.TOOLS]
        for name in names:
            self.assertIn("### `%s`" % name, actual, name)
        self.assertEqual(actual.count("### `"), len(names),
                         "docs/TOOLS.md must list every tool exactly once")

    def test_guide_toc_matches_headings(self):
        """The contents block in each guide is generated by `scripts/gen_doc_toc.py` from the
        file's own `## ` headings (fenced code blocks are skipped, so the copy-paste system
        prompt counts as data). The expected list is recomputed here, so a renamed section
        without a regenerated block fails the suite. Fix by running: python scripts/gen_doc_toc.py
        """
        sys.path.insert(0, os.path.join(ROOT, "scripts"))
        import gen_doc_toc
        for guide in ("docs/AGENT_GUIDE.md", "docs/AGENT_GUIDE.zh-CN.md"):
            text = read(guide)
            self.assertEqual(text.count(gen_doc_toc.START), 1, guide)
            self.assertEqual(text.count(gen_doc_toc.END), 1, guide)
            block = text.split(gen_doc_toc.START, 1)[1].split(gen_doc_toc.END)[0]
            entries = [l for l in block.split("\n") if l.startswith("- [")]
            expected = gen_doc_toc.render_entries(text)
            self.assertEqual(entries, expected,
                             "%s contents block is stale - run: python scripts/gen_doc_toc.py"
                             % guide)
            self.assertGreaterEqual(len(entries), 8, guide)

    def test_readme_tool_and_scenario_counts_match_the_docs(self):
        """The README quotes the tool count and the scenario count. Those sentences drift
        first when a tool is added, so they are checked against the code and the scenario
        file instead of being trusted. No number is hard-coded in the test."""
        import re
        n_tools = len(server.TOOLS)
        for readme in ("README.md", "README.zh-CN.md"):
            text = read(readme)
            for m in re.finditer(r"(\d+)\s*(?:tools|个工具)\b", text):
                self.assertEqual(int(m.group(1)), n_tools,
                                 "%s claims a wrong tool count: %s" % (readme, m.group(0)))
            for m in re.finditer(r"(\d+)\s*(?:numbered requests|条编号场景)", text):
                self.assertEqual(int(m.group(1)), self._scenario_count(),
                                 "%s claims a wrong scenario count: %s" % (readme, m.group(0)))
            # Measured 2026-11-21: the README quoted "13 error codes" while errors.HINTS
            # carried 36. Same class of drift as the tool count, so it is gated the same way.
            for m in re.finditer(r"(\d+)\s*(?:error codes|个错误码)", text):
                self.assertEqual(int(m.group(1)), len(errors.HINTS),
                                 "%s claims a wrong error-code count: %s" % (readme, m.group(0)))
        for doc, marker in (("docs/TESTING.md", "> Version:"),
                            ("docs/TESTING.zh-CN.md", "> 版本：")):
            heads = [l for l in read(doc).split("\n") if l.startswith(marker)]
            self.assertEqual(len(heads), 1, "%s needs exactly one '%s' line" % (doc, marker))
            head = heads[0]
            self.assertIn("%d" % n_tools, head,
                          "%s header does not state %d tools: %s" % (doc, n_tools, head))
            self.assertIn("%d" % self._scenario_count(), head,
                          "%s header does not state %d scenarios: %s"
                          % (doc, self._scenario_count(), head))
        # The showcase demos are the other half of the old USER_SCENARIOS file: they must exist,
        # state the tool count, and carry no numbered rows (the numbered rows belong to TESTING,
        # so a count claimed in two files cannot drift).
        for doc, marker in (("docs/DEMOS.md", "> Version:"),
                            ("docs/DEMOS.zh-CN.md", "> 版本：")):
            text = read(doc)
            heads = [l for l in text.split("\n") if l.startswith(marker)]
            self.assertEqual(len(heads), 1, "%s needs exactly one '%s' line" % (doc, marker))
            self.assertIn("%d" % n_tools, heads[0],
                          "%s header does not state %d tools: %s" % (doc, n_tools, heads[0]))
            self.assertNotRegex(text, re.compile(r"^\| \d+ \|", re.M),
                                "%s must not carry numbered rows" % doc)
            twin = "TESTING.md" if doc.endswith("DEMOS.md") else "TESTING.zh-CN.md"
            self.assertEqual(text.count("[%s](%s)" % (twin, twin)), 1,
                             "%s must link to %s exactly once" % (doc, twin))
        for old in ("docs/USER_SCENARIOS.md", "docs/USER_SCENARIOS.zh-CN.md"):
            self.assertFalse(os.path.exists(os.path.join(ROOT, old)),
                             "%s was split into DEMOS + TESTING on 2026-11-21" % old)

    @staticmethod
    def _scenario_count():
        nums = set()
        for doc in ("docs/TESTING.md", "docs/TESTING.zh-CN.md"):
            found = set(int(m.group(1)) for m in
                        re.finditer(r"^\| (\d+) \|", read(doc), re.M))
            nums = found if not nums else (nums & found)
        return len(nums)

    # Limits the app enforces today (verified against App/app/api/routes_mcp.py and
    # App/app/mcp_gateway.py on 2026-11-21). Prose pages must not contradict them: a stale
    # number in prose is invisible to every other gate, and a weak model repeats it verbatim.
    STALE_CLAIMS = [
        (r"20 frames", "frame collection is 40 per session, 10 per call", None),
        (r"session limit 20\b", "collection quota is 40", None),
        (r"\b1/20\b", "frame usage reads n/40; 1/20 belongs to delete_smart_album",
         lambda line: "删" not in line and "delete" not in line.lower()
         and "album" not in line.lower()),
        (r"20 次/会话", "the single-frame tool is 40 per session; 20 is delete_smart_album",
         lambda line: "删" not in line and "delete" not in line.lower()),
        (r"\b(13|14)\s*(?:个错误码|error codes)", "there are %d error codes", None),
        (r"\b(3[1-9]|4\d|5\d)\s*(?:条规则|rules)\b", "an album takes at most 30 rules", None),
        (r"(?<!not )published on PyPI", "the adapter is not published on PyPI", None),
        (r"top:\s*(1[3-9]|[2-9]\d)\b", "video picking top is clamped to 1..12", None),
        (r"C:[\\]+Users[\\]+(?!you\b|path\b|<|\{)",
         "a public page may only show a placeholder user path", None),
        (r"[CH]:[\\]+App-Projects", "no developer-machine absolute path in a public page", None),
        (r"一句话", "semantic search is 'a few keywords', never 'one sentence'",
         lambda line: ("语义" in line) or ("semantic" in line.lower())),
        (r"(?:^|[^1])(?:2|3)\s*小时", "the preview page lives 1 hour", None),
        (r"\b(61|70|100)\s*(?:张预览墙|photos in a sheet)", "the preview wall takes 1-60 photos",
         None),
    ]
    PROSE_PAGES = ["README.md", "README.zh-CN.md",
                   "docs/AGENT_GUIDE.md", "docs/AGENT_GUIDE.zh-CN.md",
                   "docs/QUICKSTART.md", "docs/QUICKSTART.zh-CN.md",
                   "docs/TROUBLESHOOTING.md", "docs/TROUBLESHOOTING.zh-CN.md",
                   "docs/TOOLS.md", "docs/DEMOS.md", "docs/DEMOS.zh-CN.md",
                   "docs/TESTING.md", "docs/TESTING.zh-CN.md",
                   "docs/ARCHITECTURE.md", "docs/ARCHITECTURE.zh-CN.md"]

    def test_no_stale_quota_claims_in_prose_pages(self):
        """Every page a reader (or a model) quotes must agree with the limits the app enforces.

        The CHANGELOG is excluded on purpose: it records what the limits were at each date, and
        rewriting history to today's numbers would destroy the point of the file.
        """
        n_errors = len(errors.HINTS)
        hits = []
        for doc in self.PROSE_PAGES:
            for i, raw in enumerate(read(doc).split("\n"), 1):
                # JSON examples escape the backslashes ("C:\\Users"), which lets a pattern
                # consume one of them and read the placeholder as a real name. Collapse first.
                line = raw.replace("\\\\", "\\")
                for pat, why, cond in self.STALE_CLAIMS:
                    m = re.search(pat, line, re.I)
                    if m and (cond is None or cond(line)):
                        hits.append("%s:%d [%s] %s"
                                    % (doc, i, why % n_errors if "%d" in why else why,
                                       line.strip()[:120]))
        self.assertEqual(hits, [], "stale claims in prose:\n" + "\n".join(hits))

    # Things that are fine to say internally and not in a public repo: the team's own marketing
    # vocabulary, the team's own release rhythm ("added 2026-10-25", "second round"), the team's
    # own library measurements, and the app's internal identifiers. The CHANGELOG is exempt -
    # it quotes the strings it replaced on purpose.
    INTERNAL_FRAMING = [
        "引流", "卖点", "不进 README", "只有五分钟", "写给官网首页", "桌边演示",
        "sales pitch", "sell the product", "written for a homepage", "Photographers come",
        "第三轮", "第二轮", "2026-10-25 新增", "2026-11-13 新增", "全部有回归套件",
        "added 2026-10-25", "second round 2026-10-25", "2026-10-25 evening", "added 2026-11-13",
        "真实 715", "真实 714", "851 张", "30.2 秒", "715-photo library", "714-photo library",
        "851-photo library", "1.56 GB", "r397", "_SESSION_TOOL_LIMIT", "_SESSION_FILE_LIMIT",
    ]

    def test_no_internal_framing_in_public_docs(self):
        """A public repo is read by people who are not on the team; keep the team's own voice out."""
        hits = []
        for doc in self.PROSE_PAGES:
            for i, line in enumerate(read(doc).split("\n"), 1):
                for pat in self.INTERNAL_FRAMING:
                    if pat in line:
                        hits.append("%s:%d [%s] %s" % (doc, i, pat, line.strip()[:110]))
        self.assertEqual(hits, [], "internal framing in public prose:\n" + "\n".join(hits))

    # Bilingual pairs must stay structurally aligned: same number of sections, same number of
    # table rows, same number of numbered rows. The README pair is exempt - the landing pages
    # are written for their own readers.
    BILINGUAL_PAIRS = [
        "docs/AGENT_GUIDE.md",
        "docs/QUICKSTART.md",
        "docs/TROUBLESHOOTING.md",
        "docs/DEMOS.md",
        "docs/TESTING.md",
        "docs/ARCHITECTURE.md",
    ]

    def test_bilingual_pairs_have_the_same_structure(self):
        """A reader who opens the Chinese page and the English page should see the same shape."""
        import re
        diffs = []
        for en in self.BILINGUAL_PAIRS:
            zh = en[:-3] + ".zh-CN.md"
            a, b = read(en), read(zh)
            for label, pat in (("sections", r"^## "), ("table rows", r"^\| "),
                               ("numbered rows", r"^\| [S E]?\d+[a-z]? \|")):
                ca, cb = len(re.findall(pat, a, re.M)), len(re.findall(pat, b, re.M))
                if ca != cb:
                    diffs.append("%s: %s en=%d zh=%d" % (en, label, ca, cb))
        self.assertEqual(diffs, [], "bilingual structure drift:\n" + "\n".join(diffs))

    # The repository is the open-source surface. Nothing in it may lean on vocabulary that only
    # makes sense inside the private FaceNest repository: progress-note numbers, its build
    # scripts, its gateway identifiers, its revision letters. CHANGELOG is exempt (it records
    # history written before that line was drawn), and so is this file, which quotes the very
    # patterns it forbids.
    SHIPPED_EXEMPT = {"CHANGELOG.md", "tests/test_docs.py", "scripts/publish_snapshot.py"}
    SHIPPED_SUFFIXES = (".py", ".md", ".yml", ".yaml", ".toml", ".txt", ".json", ".cfg", ".ini")
    SHIPPED_SKIP_DIRS = (".git", "data", "_backup", "build", "__pycache__", ".pytest_cache")
    INTERNAL_REFERENCES = (
        ("progress note reference", r"progress note|Progress/|商业化准备"),
        ("private-repo rule file", r"AGENTS\.md"),
        ("app build script path", r"_build/"),
        ("app source path", r"App/mcp_server|mcp_gateway"),
        ("app gateway identifier", r"_SESSION_TOOL_LIMIT|_SESSION_FILE_LIMIT"),
        ("app revision letter", r"\br\d{3,4}\b"),
    )

    def test_no_private_repo_references_in_shipped_files(self):
        hits = []
        for folder, subdirs, files in os.walk(ROOT):
            rel = os.path.relpath(folder, ROOT).replace("\\", "/")
            rel = "" if rel == "." else rel
            subdirs[:] = [d for d in subdirs if d not in self.SHIPPED_SKIP_DIRS]
            for name in files:
                path = (rel + "/" if rel else "") + name
                if path in self.SHIPPED_EXEMPT or not path.endswith(self.SHIPPED_SUFFIXES):
                    continue
                for n, line in enumerate(read(path).splitlines(), 1):
                    for label, pat in self.INTERNAL_REFERENCES:
                        if re.search(pat, line):
                            hits.append("%s:%d [%s] %s"
                                        % (path, n, label, line.strip()[:110]))
        self.assertEqual(hits, [], "shipped files lean on private-repo vocabulary:\n"
                                   + "\n".join(hits))


class CommunityFilesTest(unittest.TestCase):
    """The repository speaks to people, not only to agents.

    A public repository is judged by its front door: where to report a security problem, how to
    build and test, and what an issue report must contain. Those files drift silently like any
    other doc, so their existence, their contact address and their links are asserted here.
    """

    FRONT_DOOR = ("SECURITY.md", "CONTRIBUTING.md", "CODE_OF_CONDUCT.md")
    TEMPLATES = (".github/ISSUE_TEMPLATE/bug_report.yml",
                 ".github/ISSUE_TEMPLATE/feature_request.yml",
                 ".github/ISSUE_TEMPLATE/config.yml")
    CONTACT = "support@facenest.net"

    def test_front_door_files_exist(self):
        for path in self.FRONT_DOOR + self.TEMPLATES:
            self.assertTrue(os.path.isfile(os.path.join(ROOT, path.replace("/", os.sep))), path)

    def test_security_policy_names_the_public_contact(self):
        policy = read("SECURITY.md")
        self.assertIn(self.CONTACT, policy)
        # The git commit author address is not a contact address; it cannot receive mail.
        self.assertNotIn("eclgo@users.noreply", policy)
        # The adapter's whole network surface, stated where a reader can find it.
        self.assertIn("127.0.0.1", policy)

    def test_conduct_reports_have_their_own_subject_prefix(self):
        # Two kinds of private report share one mailbox; the prefix is what keeps them apart in
        # a shared inbox, so it is asserted, not assumed.
        coc = read("CODE_OF_CONDUCT.md")
        self.assertIn(self.CONTACT, coc)
        self.assertIn("conduct:", coc)

    def test_issue_templates_link_pages_that_exist(self):
        pat = re.compile(r"github\.com/eclgo/facenest-mcp/(?:blob/main/|security/policy)")
        for path in self.TEMPLATES:
            text = read(*path.split("/"))
            for blob_path in re.findall(
                    r"https://github\.com/eclgo/facenest-mcp/blob/main/([A-Za-z0-9_./-]+)", text):
                self.assertTrue(os.path.isfile(os.path.join(ROOT, blob_path.replace("/", os.sep))),
                                "%s links %s, which is not in the tree" % (path, blob_path))
            if "security/policy" in text:
                self.assertTrue(os.path.isfile(os.path.join(ROOT, "SECURITY.md")))
            self.assertTrue(pat.search(text) or "facenest.net" in text,
                            "%s has no link a reader can follow" % path)

    def test_templates_ask_for_the_two_answers_that_matter(self):
        bug = read(*".github/ISSUE_TEMPLATE/bug_report.yml".split("/"))
        self.assertIn("id: environment", bug)     # versions and the client name
        self.assertIn("id: reproduce", bug)       # smallest sequence that shows it
        self.assertIn("selftest", bug)            # the one line that proves reachability
        self.assertIn("label: Before posting", bug)
        config = read(*".github/ISSUE_TEMPLATE/config.yml".split("/"))
        self.assertIn("blank_issues_enabled: false", config)
        self.assertIn(self.CONTACT, config)

    def test_packaging_metadata_publishes_the_contact_address(self):
        # The account email a publisher registers with a package index is login-only: a reader
        # sees the maintainer's user name, not that address. The contact a `pip` user can find
        # is the one inside the package metadata, so it is asserted here and kept equal to the
        # address the documentation names.
        meta = read("pyproject.toml")
        self.assertIn(self.CONTACT, meta)
        self.assertNotIn("gmail.com", meta)

    def test_contributing_names_the_real_commands_and_generators(self):
        guide = read("CONTRIBUTING.md")
        self.assertIn("python -m unittest discover -s tests", guide)
        self.assertIn("type(scope)", guide)
        for script in ("gen_tools_doc.py", "gen_doc_toc.py"):
            self.assertIn(script, guide)
            self.assertTrue(os.path.isfile(os.path.join(ROOT, "scripts", script)), script)
        self.assertIn("squash", guide.lower())


